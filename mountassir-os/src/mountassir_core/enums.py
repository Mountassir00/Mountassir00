"""Controlled vocabularies of CORE. Values are stored as-is in the database."""

from __future__ import annotations

from enum import IntEnum, StrEnum
from typing import TypeVar

from .errors import ValidationError


class Classification(IntEnum):
    C0_PUBLIC = 0          # public diffusion expressly allowed
    C1_SHARED = 1          # shared with precisely authorised people/groups
    C2_CONFIDENTIAL = 2    # usable in a defined professional/personal context
    C3_PRIVATE = 3         # owner + authorised private components only (DEFAULT)
    C4_SENSITIVE = 4       # health, psychological, intimate, sensitive financial
    C5_VAULT = 5           # secrets: never stored in memory, never sent to an LLM


DEFAULT_CLASSIFICATION = Classification.C3_PRIVATE
# Nothing above C4 can ever cross the gateway, whatever an agent's grant says.
GATEWAY_HARD_CEILING = Classification.C4_SENSITIVE


class MemoryCategory(StrEnum):
    AUTOBIOGRAPHICAL = "autobiographical"
    SEMANTIC = "semantic"
    EPISODIC = "episodic"
    PROCEDURAL = "procedural"
    DECISIONAL = "decisional"
    PROSPECTIVE = "prospective"
    RELATIONAL = "relational"
    EMOTIONAL = "emotional"
    BEHAVIORAL = "behavioral"
    CREATIVE = "creative"
    PREFERENTIAL = "preferential"
    NORMATIVE = "normative"


# Minimum classification per category (privacy by default).
CATEGORY_FLOORS: dict[str, int] = {
    MemoryCategory.EMOTIONAL: Classification.C4_SENSITIVE,
}


class EpistemicType(StrEnum):
    VERIFIED_FACT = "verified_fact"
    SELF_STATEMENT = "self_statement"
    THIRD_PARTY_STATEMENT = "third_party_statement"
    PREFERENCE = "preference"
    OBSERVATION = "observation"
    INTENTION = "intention"
    HYPOTHESIS = "hypothesis"
    INFERENCE = "inference"
    PREDICTION = "prediction"
    EVALUATION_RESULT = "evaluation_result"
    ASPIRATION = "aspiration"


# Only the owner can assert these; an agent's word is never a verified fact.
OWNER_ONLY_EPISTEMIC = frozenset({EpistemicType.VERIFIED_FACT})


class AuthorType(StrEnum):
    OWNER = "owner"            # written or submitted by the owner
    AI = "ai"                  # generated by an AI system
    THIRD_PARTY = "third_party"
    SYSTEM = "system"
    UNKNOWN = "unknown"


class MemoryStatus(StrEnum):
    PROPOSED = "proposed"          # candidate, invisible to agents until validated
    VALIDATED = "validated"
    REJECTED = "rejected"          # content wiped, hash kept to block re-proposal
    NEEDS_REVIEW = "needs_review"  # lost part of its evidence; hidden from agents
    SUPERSEDED = "superseded"      # was true, no longer is (valid_until set)


class Scope(StrEnum):
    MEMORY_READ = "memory:read"
    MEMORY_PROPOSE = "memory:propose"
    DOCUMENTS_READ = "documents:read"
    CONTEXT_CREATE = "context:create"
    THIRD_PARTY_READ = "third_party:read"


class Flag(StrEnum):
    GATEWAY_STOPPED = "gateway_stopped"
    WRITES_FROZEN = "writes_frozen"
    LEARNING_PAUSED = "learning_paused"


E = TypeVar("E", bound=StrEnum)


def parse_enum(enum: type[E], value: str, field: str) -> E:
    try:
        return enum(value)
    except ValueError:
        allowed = ", ".join(e.value for e in enum)
        raise ValidationError(f"invalid {field} '{value}'; allowed: {allowed}") from None


def parse_classification(value: int | str | None) -> int | None:
    if value is None:
        return None
    try:
        v = int(str(value).upper().lstrip("C"))
    except ValueError:
        raise ValidationError(f"invalid classification '{value}' (use 0-5 or C0-C5)") from None
    if not 0 <= v <= 5:
        raise ValidationError(f"invalid classification '{value}' (use 0-5 or C0-C5)")
    return v
